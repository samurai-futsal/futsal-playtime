export function vGuide() {
  const toc = SECS.map(([id, t], i) => `<a href="#" data-gj="${id}">${i + 1}. ${esc(t)}</a>`).join('');
  return {
    active: 'settings',
    html: `<div class="guide"><div class="crumb noprint"><a class="btn sm mpback" href="#/settings">‹ 設定</a> 使い方</div>
      <div class="row between"><h1>使い方（使用説明書）</h1><button class="btn noprint" id="gPrint">PDFで書き出す</button></div>
      <p class="mu">フットサル出場時間管理アプリの使い方です。アプリの中にあるので、ネットがない会場でも読めます。</p>
      <nav class="gtoc noprint">${toc}</nav>
      ${SECS.map(([id, t], i) => `<section class="gsec" id="g-${id}"><h2>${i + 1}. ${esc(t)}</h2>${SECS[i][2]}</section>`).join('')}</div>`,
    bind: (root) => {
      root.querySelector('#gPrint').onclick = () => window.print();
      root.querySelectorAll('[data-gj]').forEach((a) => a.onclick = (e) => { e.preventDefault(); root.querySelector('#g-' + a.dataset.gj)?.scrollIntoView({ behavior: 'smooth' }); });
    },
  };
}
